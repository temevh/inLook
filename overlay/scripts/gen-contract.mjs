// Generates the contract mirrors from shared/*.schema.json.
//   node scripts/gen-contract.mjs ts   -> src/shared/contract.gen.ts
//   node scripts/gen-contract.mjs py   -> ../shared/generated/contract_models.py (pydantic v2)
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { compile } from "json-schema-to-typescript";

const shared = new URL("../../shared/", import.meta.url).pathname;
const mode = process.argv[2];

if (mode === "ts") {
  const banner = "/* GENERATED by `npm run gen:contract` from shared/*.schema.json. Do not edit. */";
  const opts = { cwd: shared, bannerComment: banner, additionalProperties: false };
  const event = await compile(JSON.parse(readFileSync(shared + "event.schema.json", "utf8")), "InlookEvent", opts);
  // api.schema.json only has $defs; root them so every definition is emitted.
  const api = JSON.parse(readFileSync(shared + "api.schema.json", "utf8"));
  const apiTs = await compile(
    { ...api, type: "object", properties: Object.fromEntries(Object.keys(api.$defs).map((k) => [k, { $ref: `#/$defs/${k}` }])) },
    "Api", { ...opts, bannerComment: "" });
  writeFileSync(new URL("../src/shared/contract.gen.ts", import.meta.url), event + "\n" + apiTs);
} else if (mode === "py") {
  // datamodel-codegen needs one file with no external refs: inline card + api defs.
  const read = (n) => JSON.parse(readFileSync(shared + n + ".schema.json", "utf8"));
  const { $schema, ...card } = read("card");
  const event = JSON.parse(JSON.stringify(read("event")).replaceAll('"card.schema.json"', '"#/$defs/HudCard"'));
  event.$defs = { ...event.$defs, HudCard: card, ...read("api").$defs };
  const input = mkdtempSync(tmpdir() + "/inlook-contract-") + "/bundle.json";
  writeFileSync(input, JSON.stringify(event));
  mkdirSync(shared + "generated", { recursive: true });
  const args = ["--input", input, "--input-file-type", "jsonschema", "--output-model-type", "pydantic_v2.BaseModel",
    "--use-annotated", "--formatters", "black", "isort", "--disable-timestamp",
    "--output", shared + "generated/contract_models.py"];
  // datamodel-codegen: PATH, else uvx, else nix.
  for (const [cmd, ...pre] of [["datamodel-codegen"], ["uvx", "--from", "datamodel-code-generator", "datamodel-codegen"],
    ["nix", "run", "nixpkgs#datamodel-code-generator", "--"]]) {
    const r = spawnSync(cmd, [...pre, ...args], { stdio: "inherit" });
    if (!r.error) process.exit(r.status ?? 1);
  }
  console.error("datamodel-codegen not found (tried PATH, uvx, nix)");
  process.exit(1);
} else {
  console.error("usage: gen-contract.mjs ts|py"); process.exit(2);
}
